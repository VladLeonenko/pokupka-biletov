export function buildVenueLandingCopy(
  venueName: string,
  opts?: { slug?: string; address?: string | null },
): VenueLandingCopy {
  const name = String(venueName || '').trim() || 'Площадка';
  const slug = String(opts?.slug || '').trim().toLowerCase();
  const address = String(opts?.address || '').trim();

  const title = `${name} — афиша и билеты онлайн`;
  const description = address
    ? `Билеты в «${name}» (${address}): расписание, цены. ${MECHANICS}.`
    : `Билеты в «${name}»: афиша, расписание и цены. ${MECHANICS}.`;

  const aboutFromMap = slug ? ABOUT_BY_SLUG[slug] : undefined;
  const about =
    aboutFromMap ||
    (address
      ? `Купить билеты в «${name}» онлайн: ближайшие события, выбор мест на схеме зала и электронный билет на e-mail. Адрес: ${address}.`
      : `Купить билеты в «${name}» онлайн: актуальная афиша, выбор мест на схеме зала, безопасная оплата и электронный билет на e-mail.`);

  return {
    title: title.length > 70 ? `${name} — билеты, афиша онлайн` : title,
    description: description.slice(0, 160),
    h1: name,
    about,
    keywords: `${name.toLowerCase()} билеты, афиша ${name.toLowerCase()}, купить билет`,
  };
}
